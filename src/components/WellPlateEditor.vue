    // export exactly, which is the verified-correct reference.
    const groupedTransfers = {};
    allTransfers.forEach(t => {
        const formattedVol = Number(t.volume.toFixed(3));
        const key = `${t.sourceKey}__${t.plateRef}__${formattedVol}`;
        if (!groupedTransfers[key]) groupedTransfers[key] = { sourceKey: t.sourceKey, plateRef: t.plateRef, volume: formattedVol, cavities: [] };
        groupedTransfers[key].cavities.push(t.destCavity);
    });

    // Same step order as the single-plate export: water first, then compounds
    // alphabetically, all of one compound's steps together. The sort is stable, so
    // within one compound the plates keep the order they were selected in.
    const orderedGroups = Object.values(groupedTransfers).sort((a, b) => {
        const sa = sourceMap[a.sourceKey], sb = sourceMap[b.sourceKey];
        if (sa.isWater !== sb.isWater) return sa.isWater ? -1 : 1;
        const byName = (sa.sourceName || '').localeCompare(sb.sourceName || '', undefined, { sensitivity: 'base' });
        return byName !== 0 ? byName : a.volume - b.volume;
    });

    let stepIdx = 1;
    for (const group of orderedGroups) {
        const srcData = sourceMap[group.sourceKey];
        // Emit one step per de-duplicated round so a well never repeats within a step.
        for (const roundCavities of onpCavityRounds(group.cavities)) {
            steps.push({
                index: stepIdx++, actionTypeId: "PIPETTING",
                action: {
                    type: "PIPETTING",
                    sources: [{ labwareRef: srcData.labwareRef, cavities: [{ row: 1, column: 1 }], customPipettingPolicy: false }],
                    destinations: [{ labwareRef: group.plateRef, cavities: roundCavities, customPipettingPolicy: false }],
                    params: {
                        volume: { value: group.volume, unit: "uL" }, mode: "forward", aspirationSpeed: "normal", dispensingSpeed: "normal",
                        airTopCushion: false, airBottomCushion: false, tipChangeBeginning: true, tipChangeBetween: true, tipWithFilter: false,
                        movingSpeed: "normal", verifyTip: false, blowOut: true, blowOutPause: false, tipTouch: false, armSpeed: "normal",
                        preciseAspirationSpeed: 5, preciseDispensingSpeed: 5, preciseFluidicSpeedEnabled: false
                    },
                    mixingSource: { enabled: false, times: 3, speed: "normal", volume: { value: 0, unit: "uL" }, preciseSpeed: 5, preciseSpeedEnabled: false },
                    tipPositionSource: { position: "liquid", customHeight: false, customHeightValue: 0, avoidTouch: false },
                    mixingDest: { enabled: false, times: 3, speed: "normal", volume: { value: 0, unit: "uL" }, preciseSpeed: 5, preciseSpeedEnabled: false },
                    tipPositionDest: { position: "bottom", customHeight: false, customHeightValue: 0, avoidTouch: false }
                },
                ref: onpHex(16), groupStepRefs: []
            });
        }
    }

    const protocolName = (groupExportName.value || "Grouped Protocol").trim() || "Grouped Protocol";
    const baseProtocol = {
        name: protocolName, description: "Exported from CTI Lab Assistant",
        params: { pipettingPolicy: "rbr", filterTips: false, safeTipOverfly: false }, errors: 0,
        steps, labwares, reagents, samples: [], pipettingPolicy: "rbr", isDynamic: false, version: "1.2.0"
    };

    baseProtocol.checksum = onpMd5(JSON.stringify(baseProtocol));

    const blob = new Blob([JSON.stringify(baseProtocol)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url; link.download = `RobotProtocol_${protocolName.replace(/\s+/g, '_')}.onp`;
    document.body.appendChild(link); link.click(); document.body.removeChild(link);
    showGroupExport.value = false;
};
</script>

