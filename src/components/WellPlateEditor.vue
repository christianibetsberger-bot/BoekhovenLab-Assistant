// --- Grouped Multi-Plate Robot Protocol (.onp) Export ---
// Combines several well plates into ONE .onp. Each plate becomes its own target
// labware, but sources are de-duplicated GLOBALLY by stock identity (code + name):
// a stock shared between plates appears once, holds the summed volume of all plates,
// and every plate's pipetting steps draw from that single source labware.
// This path is fully independent — the single-plate exportAndrewPlus is untouched.

const onpMd5 = function(d) {
    let r = /[\x80-\xFF]/g;
    if (r.test(d)) d = unescape(encodeURI(d));
    let h0 = 0x67452301, h1 = 0xEFCDAB89, h2 = 0x98BADCFE, h3 = 0x10325476;
    const rots = [7, 12, 17, 22, 5, 9, 14, 20, 4, 11, 16, 23, 6, 10, 15, 21];
    const k = [];
    for (let i = 0; i <= 63; i++) k[i] = (Math.abs(Math.sin(i + 1)) * 0x100000000) | 0;
    let words = [];
    for (let i = 0; i < d.length; i++) words[i >> 2] |= (d.charCodeAt(i) & 0xFF) << ((i % 4) * 8);
    let len = d.length * 8;
    words[len >> 5] |= 0x80 << (len % 32);
    words[(((len + 64) >>> 9) << 4) + 14] = len;
    for (let i = 0; i < words.length; i += 16) {
        let a = h0, b = h1, c = h2, d2 = h3;
        for (let j = 0; j <= 63; j++) {
            let f, g = j;
            if (j < 16) { f = (b & c) | ((~b) & d2); }
            else if (j < 32) { f = (d2 & b) | ((~d2) & c); g = (5 * j + 1) % 16; }
            else if (j < 48) { f = b ^ c ^ d2; g = (3 * j + 5) % 16; }
            else { f = c ^ (b | (~d2)); g = (7 * j) % 16; }
            let temp = d2; d2 = c; c = b;
            let x = a + f + k[j] + (words[i + g] || 0);
            let rot = rots[(Math.floor(j / 16) * 4) + (j % 4)];
            b = b + ((x << rot) | (x >>> (32 - rot)));
            a = temp;
        }
        h0 = (h0 + a) | 0; h1 = (h1 + b) | 0; h2 = (h2 + c) | 0; h3 = (h3 + d2) | 0;
    }
    const hex = (x) => {
        let s = '';
        for (let i = 0; i < 4; i++) s += ((x >> (i * 8)) & 0xFF).toString(16).padStart(2, '0');
        return s;
    };
    return hex(h0) + hex(h1) + hex(h2) + hex(h3);
};

const onpHex = (len) => [...Array(len)].map(() => Math.floor(Math.random() * 16).toString(16)).join('');
const onpUuid = () => 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, c => {
    const r = Math.random() * 16 | 0, v = c === 'x' ? r : (r & 0x3 | 0x8);
    return v.toString(16);
});

// Split a step's cavity list into "rounds" so a given well never appears twice within
// one PIPETTING step. A well that receives the same stock+volume N times (e.g. a matrix
// diagonal cell fed by both its row and its column component) is spread across N steps —
// the robot still dispenses it N times (total volume unchanged), but no single step lists
// the same well twice. Duplicate cavities in one step otherwise serialise as overlapping
// cavity ranges (e.g. "E1:E5, E5:E7") that Andrew+ / OneLab mis-expands, double-counting
// the wells around the overlap and reporting inflated well volumes.
// Declared as a function so it is hoisted for use by exportAndrewPlus (defined above).
function onpCavityRounds(cavities) {
    const rounds = [];
    const seen = [];
    for (const cav of cavities) {
        const id = `${cav.row}-${cav.column}`;
        let r = 0;
        while (seen[r] && seen[r].has(id)) r++;
        if (!seen[r]) { seen[r] = new Set(); rounds[r] = []; }
        seen[r].add(id);
        rounds[r].push(cav);
    }
    return rounds;
}

// Parse a single plate's wells into a flat transfer list. Mirrors the parsing in
// exportAndrewPlus but additionally extracts the stock [code] for cross-plate dedup.
const onpParsePlateTransfers = (plate) => {
    const transfers = [];
    const parser = new DOMParser();
    for (const [wId, html] of Object.entries(plate.wells || {})) {
        if (!html || html.trim() === '') continue;
        const doc = parser.parseFromString(html, 'text/html');
        const row = wId.charCodeAt(0) - 64;
        const col = parseInt(wId.substring(1));
        const destCavity = { row, column: col };

        doc.querySelectorAll('.inv-ref').forEach(ref => {
            let text = ref.innerText;
            let labwareAttr = ref.getAttribute('data-labware');
            let labwareUuid = (labwareAttr && labwareAttr.trim() !== '') ? labwareAttr : onpConfig.value.defaultSourceLabwareUuid;

            let codeMatch = text.match(/\[(.*?)\]/);
            let code = codeMatch ? codeMatch[1].trim() : '';

            let nameMatch = text.match(/\]\s*(.*?)\s*\(/);
            let name = nameMatch ? nameMatch[1].trim() : text.replace(/\[.*?\]/, '').replace(/\(.*?\)/, '').trim();

            let concValue = 100; let concUnit = "uM";
            let concMatch = text.match(/\(([\d\.,]+)\s*([^)]+)\)/);
            if (concMatch) {
                concValue = parseFloat(concMatch[1].replace(',', '.'));
                concUnit = concMatch[2].trim().replace('µ', 'u');
            }

            let nextText = ref.nextSibling ? ref.nextSibling.textContent : "";
            let volMatch = nextText.match(/([\d\.]+)\s*(µL|mL|L)/);
            if (name && volMatch) {
                let vol = parseFloat(volMatch[1]);
                if (volMatch[2] === 'mL') vol *= 1000;
                if (volMatch[2] === 'L') vol *= 1000000;
                if (vol > 0) transfers.push({ sourceName: name, code, destCavity, volume: vol, type: 'reagent', concValue, concUnit, labwareUuid });
            }
        });

        doc.querySelectorAll('strong').forEach(st => {
            if (st.innerText.includes('MQ H₂O') || st.innerText.includes('MQ Water')) {
                let volText = "";
                if (st.nextElementSibling && st.nextElementSibling.tagName === 'SPAN') volText = st.nextElementSibling.innerText;
                else if (st.nextSibling && st.nextSibling.nodeType === Node.TEXT_NODE) volText = st.nextSibling.textContent;
                let volMatch = volText.match(/([\d\.]+)\s*(µL|mL|L)/);
                if (volMatch) {
                    let vol = parseFloat(volMatch[1]);
                    if (volMatch[2] === 'mL') vol *= 1000;
                    if (volMatch[2] === 'L') vol *= 1000000;
                    if (vol > 0) transfers.push({ sourceName: 'Water', code: '', destCavity, volume: vol, type: 'water', labwareUuid: onpConfig.value.waterSourceLabwareUuid });
                }
            }
        });
    }
    return transfers;
};

