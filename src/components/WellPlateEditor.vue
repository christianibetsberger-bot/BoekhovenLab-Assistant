// Liquid the well names but that carries no chip. It is NOT in the Σ above, because
// the robot exporters skip it too — the Σ has to stay a description of the plate that
// will actually be built. Saying so is the point: an unexplained short total is what
// sent a user looking for a bug, and the honest answer is "this much is unlinked".
const wellUnlinked = (plate) => {
    if (!plate?.selectedWell) return { total: 0, names: '' }
    const rows = unlinkedVolumes(plate.wells[plate.selectedWell] || '')
    return {
        total: rows.reduce((s, r) => s + r.volume, 0),
        names: [...new Set(rows.map(r => r.name))].join(', '),
    }
}

// Editing the stock used in THIS well. The inventory is untouched: a well records
// what was pipetted into it, which may be an older or a freshly diluted stock.
const setWellEntry = (plate, index, field, value) => {
    if (!plate?.selectedWell) return
    const entries = parseWellHtml(plate.wells[plate.selectedWell] || '')
    if (!entries[index]) return
    const v = parseFloat(String(value).replace(',', '.'))
    if (field === 'unit') entries[index].unit = String(value || '').trim()
    else if (isFinite(v) && v >= 0) entries[index][field] = v
    else return
    plate.wells[plate.selectedWell] = buildWellHtml(entries, { inventory: store.inventory, showFinal: true })
    syncWellEditor(plate)
    store.saveWorkspaceState()
}

// Re-make the selected well at a different total volume. Every volume — fill-up
// included — is multiplied by the same factor, so every final concentration stays
// exactly what it was; only the amount of liquid changes. This is the second half
// of copying a well: paste it, then shrink it to the volume the new plate runs at.
const scaleWellTo = (plate, value) => {
    if (!plate?.selectedWell) return
    const target = parseFloat(String(value).replace(',', '.'))
    const entries = parseWellHtml(plate.wells[plate.selectedWell] || '')
    const scaled = scaleEntriesToTotal(entries, target)
    if (!scaled) {
        if (String(value).trim() !== '') store.toast?.('Nothing to scale — the well needs parsed volumes and a positive target')
        return
    }
    plate.wells[plate.selectedWell] = buildWellHtml(scaled, { inventory: store.inventory, showFinal: true })
    syncWellEditor(plate)
    store.saveWorkspaceState()
    store.toast?.(`Well ${plate.selectedWell} scaled to ${target} µL — same concentrations, adjusted volumes`)
}

